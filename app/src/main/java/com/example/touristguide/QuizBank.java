    /** Questions for one difficulty and an optional category (null = all categories), shuffled. */
    public static List<QuizQuestion> select(QuizQuestion.Category category,
                                            QuizQuestion.Difficulty difficulty, int limit, Random random) {
        List<QuizQuestion> pool = new ArrayList<>();
        for (QuizQuestion q : QUESTIONS) {
            if (q.difficulty == difficulty && (category == null || q.category == category)) pool.add(q);
        }
        Collections.shuffle(pool, random);
        return pool.size() > limit ? new ArrayList<>(pool.subList(0, limit)) : pool;
    }
